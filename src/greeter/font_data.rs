/// (base character, accent kind) for a precomposed Latin-1-ish letter.
pub fn decompose(ch: char) -> Option<(char, Accent)> {
    Some(match ch {
        '\u{e1}' => ('a', Accent::Acute),
        '\u{e9}' => ('e', Accent::Acute),
        '\u{ed}' => ('\u{131}', Accent::Acute),
        '\u{f3}' => ('o', Accent::Acute),
        '\u{fa}' => ('u', Accent::Acute),
        '\u{e0}' => ('a', Accent::Grave),
        '\u{e8}' => ('e', Accent::Grave),
        '\u{fc}' => ('u', Accent::Diaeresis),
        '\u{f1}' => ('n', Accent::Tilde),
        '\u{c1}' => ('A', Accent::Acute),
        '\u{c9}' => ('E', Accent::Acute),
        '\u{cd}' => ('I', Accent::Acute),
        '\u{d3}' => ('O', Accent::Acute),
        '\u{da}' => ('U', Accent::Acute),
        '\u{dc}' => ('U', Accent::Diaeresis),
        '\u{d1}' => ('N', Accent::Tilde),
        '\u{bf}' => ('?', Accent::Flip),
        '\u{a1}' => ('!', Accent::Flip),
        _ => return None,
    })
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Accent { Acute, Grave, Diaeresis, Tilde, Flip }
